    /// <summary>
    /// returns a bitboard containing all squares a knight could reach
    /// </summary>
    public static ulong KnightAttacks(int sq, ulong block=0) => KnightAttackBB[sq];
    /// <summary>
    /// returns a bitboard containing all squares a king could reach
    /// </summary>
    public static ulong KingAttacks(int sq, ulong block=0) => KingAttackBB[sq];

    /// <summary>
    /// returns a bitboard containing all squares a bishop could reach
    /// all pieces blocking the movement are available for capture on the bitboard
    /// </summary>
    public static ulong BishopAttacks(int sq, ulong block)
    {
        ulong key = getKey(bishopMagics[sq], bishopMasks[sq], block, fancyBishopBits[sq]);
        return bishopMagicLookup[sq][key];
    }

    /// <summary>
    /// returns a bitboard containing all squares a rook could reach
    /// all pieces blocking the movement are available for capture on the bitboard
    /// </summary>
    public static ulong RookAttacks(int sq, ulong block)
    {
        ulong key = getKey(rookMagics[sq], rookMasks[sq], block, fancyRookBits[sq]);
        return rookMagicLookup[sq][key];
    }

    /// <summary>
    /// returns a bitboard containing all squares a queen could reach
    /// all pieces blocking the movement are available for capture on the bitboard
    /// </summary>
    public static ulong QueenAttacks(int sq, ulong block)
    {
        return BishopAttacks(sq, block) | RookAttacks(sq, block);
    }

    /// <summary>
    /// returns a bitboard containing reachable squares by PieceType
    /// </summary>
    public static ulong PieceAttacks(pos p, int pt, int sq) 
    {
        return pt switch {
            PAWN   => PseudoPawnMoves(p, sq),
            KNIGHT => KnightAttacks(sq),
            BISHOP => BishopAttacks(sq, p.get_blocker()),
            ROOK   => RookAttacks(sq, p.get_blocker()),
            QUEEN  => BishopAttacks(sq, p.get_blocker()) | RookAttacks(sq, p.get_blocker()),
            KING   => KingAttacks(sq),
            _      => 0
        };
    }

    private static ulong PseudoPawnMoves(pos p, int sq) 
    {
        ulong empty = ~p.get_blocker();
        // push moves
        ulong push = up(1ul << sq, p.us) & empty;
        if ((push & (p.us==WHITE ? Rank3 : Rank6)) != 0) {
            push |= up(push, p.us) & empty;
        }

        // capture moves
        ulong captures = PawnAttacks[p.us][sq] & p.colorBB[1-p.us];
        if (sq == p.ep) {
            captures |= 1ul << sq;
        }
        return captures | push;
    }

