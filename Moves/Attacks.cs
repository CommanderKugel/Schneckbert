    private static ulong indexToBlocker (int blockIdx, ulong mask, int maskPopCnt)
    {
        ulong block = 0;
        for (int i=0; i<maskPopCnt; i++)
        {
            int sqIdx = popLsb(ref mask);

            if ((blockIdx & (1 << i)) != 0)
                block |= 1ul << sqIdx;
        }
        return block;
    }
    private static ulong BishopAttacksRay(int sq, ulong block) {
        ulong b = 1ul << sq;
        return Ray(b, block, nw) | Ray(b, block, sw) | Ray(b, block, ne) | Ray(b, block, se);
    }
    private static ulong RookAttacksRay(int sq, ulong block) {
        ulong b = 1ul << sq;
        return Ray(b, block, north) | Ray(b, block, south) | Ray(b, block, east) | Ray(b, block, west);
    }

    private static ulong getKey(ulong magic, ulong mask, ulong block, int shift) => (magic * (mask & block)) >> (64 - shift);


    public static void init()
    {
        bishopMagicLookup = new ulong[64][];
        rookMagicLookup   = new ulong[64][];

        for (int sq=0; sq<64; sq++)
        {
            bishopMagicLookup[sq] = new ulong[1 << fancyBishopBits[sq]];
            rookMagicLookup[sq]   = new ulong[1 << fancyRookBits[sq]];

            foreach (bool isRook in new[] {false, true})
            {                
                ulong mask  = isRook ? rookMasks[sq]     : bishopMasks[sq];
                ulong magic = isRook ? rookMagics[sq]    : bishopMagics[sq];
                int   bits  = isRook ? fancyRookBits[sq] : fancyBishopBits[sq];

                int maskPopCnt = popCount(mask);
                int occCount = 1 << maskPopCnt;

                for (int i=0; i<occCount; i++)
                {
                    ulong block = indexToBlocker(i, mask, maskPopCnt);
                    ulong attack = isRook ? RookAttacksRay(sq, block) : BishopAttacksRay(sq, block);
                    ulong key = getKey(magic, mask, block, bits);

                    if (isRook) rookMagicLookup[sq][key]   = attack;
                    else        bishopMagicLookup[sq][key] = attack;             
                }
            }
        }
    }
